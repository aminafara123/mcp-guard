"""Render a scan result as JSON or Markdown. Pure, deterministic."""
import json

_EMOJI = {"critical": "CRITICAL", "high": "HIGH", "medium": "MEDIUM",
          "low": "LOW", "none": "NONE"}


def to_json(result, indent=2):
    return json.dumps(result, indent=indent, sort_keys=True)


def to_markdown(result, ai_summary=None):
    r = result
    lines = [
        "# MCP-Guard scan report",
        "",
        "- **Server:** `%s`" % r["server"],
        "- **Tools scanned:** %d" % r["tool_count"],
        "- **Overall risk rating:** **%s**" % _EMOJI.get(r["risk_rating"], r["risk_rating"].upper()),
        "- **Findings:** %d" % len(r["findings"]),
        "",
        "| severity | count |",
        "| --- | --- |",
    ]
    for sev in ("critical", "high", "medium", "low"):
        lines.append("| %s | %d |" % (sev, r["severity_counts"].get(sev, 0)))
    lines += ["", "## Findings", ""]
    if not r["findings"]:
        lines.append("_No risky tools matched the deterministic rules._")
    else:
        lines += ["| tool | rule | severity | why | remediation |",
                  "| --- | --- | --- | --- | --- |"]
        for f in r["findings"]:
            lines.append("| `%s` | %s | %s | %s | %s |" % (
                f["tool"], f["rule"], f["severity"],
                f["why"].replace("|", "\\|"), f["remediation"].replace("|", "\\|")))
    if ai_summary:
        lines += ["", "## AI-generated summary",
                  "",
                  "> **AI-GENERATED — not verified. A human must review before acting.**",
                  "",
                  ai_summary.strip()]
    lines += ["", "---",
              "_Report generated by MCP-Guard deterministic rules. This is a triage aid, "
              "not a certification of safety; a human must review all findings._", ""]
    return "\n".join(lines)
